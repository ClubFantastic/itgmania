void RageDisplay_Vulkan::DrawQuadsInternal(const RageSpriteVertex v[], int iNumVerts)
{
	if (iNumVerts == 0) return;

	int iNumQuads = iNumVerts / 4;
	EnsureQuadIBO(iNumQuads);

	BindPipelineForCurrentState();
	FlushPushConstants();
	BindCurrentTexture();
	UploadVertices(v, iNumVerts);

	auto &frame = m_ctx.frames[m_ctx.currentFrame];
	vkCmdSetPrimitiveTopology(frame.commandBuffer, VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST);
	vkCmdBindIndexBuffer(frame.commandBuffer, m_quadIBO, 0, VK_INDEX_TYPE_UINT16);
	vkCmdDrawIndexed(frame.commandBuffer, iNumQuads * 6, 1, 0, 0, 0);
}

void RageDisplay_Vulkan::DrawQuadStripInternal(const RageSpriteVertex v[], int iNumVerts)
{
	if (iNumVerts < 4) return;

	BindPipelineForCurrentState();
	FlushPushConstants();
	BindCurrentTexture();
	UploadVertices(v, iNumVerts);

	auto &frame = m_ctx.frames[m_ctx.currentFrame];
	vkCmdSetPrimitiveTopology(frame.commandBuffer, VK_PRIMITIVE_TOPOLOGY_TRIANGLE_STRIP);
	vkCmdDraw(frame.commandBuffer, iNumVerts, 1, 0, 0);
}

void RageDisplay_Vulkan::DrawFanInternal(const RageSpriteVertex v[], int iNumVerts)
{
	if (iNumVerts < 3) return;

	// Convert fan to triangle list (fan topology is optional in Vulkan)
	int iNumTriangles = iNumVerts - 2;
	std::vector<RageSpriteVertex> tris(iNumTriangles * 3);
	for (int i = 0; i < iNumTriangles; i++)
	{
		tris[i * 3 + 0] = v[0];
		tris[i * 3 + 1] = v[i + 1];
		tris[i * 3 + 2] = v[i + 2];
	}

	BindPipelineForCurrentState();
	FlushPushConstants();
	BindCurrentTexture();
	UploadVertices(tris.data(), (int)tris.size());

	auto &frame = m_ctx.frames[m_ctx.currentFrame];
	vkCmdSetPrimitiveTopology(frame.commandBuffer, VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST);
	vkCmdDraw(frame.commandBuffer, (uint32_t)tris.size(), 1, 0, 0);
}

