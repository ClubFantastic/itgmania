bool RageDisplay_Vulkan::CreateInstance()
{
	VkApplicationInfo appInfo = {};
	appInfo.sType = VK_STRUCTURE_TYPE_APPLICATION_INFO;
	appInfo.pApplicationName = "ITGmania";
	appInfo.applicationVersion = VK_MAKE_VERSION(1, 0, 0);
	appInfo.pEngineName = "Rage";
	appInfo.engineVersion = VK_MAKE_VERSION(1, 0, 0);
	appInfo.apiVersion = VK_API_VERSION_1_3; // 1.3 for extended dynamic state + negative viewport

	// Get SDL-required extensions
	uint32_t sdlExtCount = 0;
	const char *const *sdlExts = SDL_Vulkan_GetInstanceExtensions(&sdlExtCount);
	std::vector<const char *> extensions(sdlExts, sdlExts + sdlExtCount);

	std::vector<const char *> layers;

#ifdef DEBUG
	extensions.push_back(VK_EXT_DEBUG_UTILS_EXTENSION_NAME);
	layers.push_back("VK_LAYER_KHRONOS_validation");
#endif

	VkInstanceCreateInfo ci = {};
	ci.sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO;
	ci.pApplicationInfo = &appInfo;
	ci.enabledExtensionCount = (uint32_t)extensions.size();
	ci.ppEnabledExtensionNames = extensions.data();
	ci.enabledLayerCount = (uint32_t)layers.size();
	ci.ppEnabledLayerNames = layers.data();

	if (vkCreateInstance(&ci, nullptr, &m_ctx.instance) != VK_SUCCESS)
		return false;

#ifdef DEBUG
	// Setup debug messenger
	VkDebugUtilsMessengerCreateInfoEXT debugCI = {};
	debugCI.sType = VK_STRUCTURE_TYPE_DEBUG_UTILS_MESSENGER_CREATE_INFO_EXT;
	debugCI.messageSeverity = VK_DEBUG_UTILS_MESSAGE_SEVERITY_WARNING_BIT_EXT |
	                          VK_DEBUG_UTILS_MESSAGE_SEVERITY_ERROR_BIT_EXT;
	debugCI.messageType = VK_DEBUG_UTILS_MESSAGE_TYPE_GENERAL_BIT_EXT |
	                      VK_DEBUG_UTILS_MESSAGE_TYPE_VALIDATION_BIT_EXT |
	                      VK_DEBUG_UTILS_MESSAGE_TYPE_PERFORMANCE_BIT_EXT;
	debugCI.pfnUserCallback = VulkanDebugCallback;

	auto createFunc = (PFN_vkCreateDebugUtilsMessengerEXT)vkGetInstanceProcAddr(m_ctx.instance, "vkCreateDebugUtilsMessengerEXT");
	if (createFunc)
		createFunc(m_ctx.instance, &debugCI, nullptr, &m_ctx.debugMessenger);
#endif

	// Create surface via SDL
	auto *pWind = dynamic_cast<LowLevelWindow_SDL *>(g_pWind);
	if (!pWind || !SDL_Vulkan_CreateSurface(pWind->GetWindow(), m_ctx.instance, nullptr, &m_ctx.surface))
		return false;

	return true;
}

bool RageDisplay_Vulkan::SelectPhysicalDevice()
{
	uint32_t count = 0;
	vkEnumeratePhysicalDevices(m_ctx.instance, &count, nullptr);
	if (count == 0) return false;

	std::vector<VkPhysicalDevice> devices(count);
	vkEnumeratePhysicalDevices(m_ctx.instance, &count, devices.data());

	for (auto &dev : devices)
	{
		// Find a queue family that supports graphics + present
		uint32_t qfCount = 0;
		vkGetPhysicalDeviceQueueFamilyProperties(dev, &qfCount, nullptr);
		std::vector<VkQueueFamilyProperties> qfProps(qfCount);
		vkGetPhysicalDeviceQueueFamilyProperties(dev, &qfCount, qfProps.data());

		int graphicsFamily = -1, presentFamily = -1;
		for (uint32_t i = 0; i < qfCount; i++)
		{
			if (qfProps[i].queueFlags & VK_QUEUE_GRAPHICS_BIT)
				graphicsFamily = i;

			VkBool32 presentSupport = VK_FALSE;
			vkGetPhysicalDeviceSurfaceSupportKHR(dev, i, m_ctx.surface, &presentSupport);
			if (presentSupport)
				presentFamily = i;
		}

		if (graphicsFamily >= 0 && presentFamily >= 0)
		{
			m_ctx.physicalDevice = dev;
			m_ctx.graphicsQueueFamily = graphicsFamily;
			m_ctx.presentQueueFamily = presentFamily;

			VkPhysicalDeviceProperties props;
			vkGetPhysicalDeviceProperties(dev, &props);
			LOG->Info("Vulkan: Selected GPU: %s", props.deviceName);
			return true;
		}
	}
	return false;
}

bool RageDisplay_Vulkan::CreateLogicalDevice()
{
	std::vector<VkDeviceQueueCreateInfo> queueCIs;
	float priority = 1.0f;

	std::vector<uint32_t> uniqueFamilies = {m_ctx.graphicsQueueFamily};
	if (m_ctx.presentQueueFamily != m_ctx.graphicsQueueFamily)
		uniqueFamilies.push_back(m_ctx.presentQueueFamily);

	for (auto family : uniqueFamilies)
	{
		VkDeviceQueueCreateInfo qCI = {};
		qCI.sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO;
		qCI.queueFamilyIndex = family;
		qCI.queueCount = 1;
		qCI.pQueuePriorities = &priority;
		queueCIs.push_back(qCI);
	}

	const char *deviceExts[] = {VK_KHR_SWAPCHAIN_EXTENSION_NAME};

	VkPhysicalDeviceFeatures features = {};
	features.fillModeNonSolid = VK_TRUE; // for wireframe

	// Enable Vulkan 1.3 extended dynamic state
	VkPhysicalDeviceVulkan13Features features13 = {};
	features13.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_3_FEATURES;
	features13.dynamicRendering = VK_TRUE;
	features13.synchronization2 = VK_TRUE;

	VkPhysicalDeviceExtendedDynamicStateFeaturesEXT extDynState = {};
	extDynState.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_EXTENDED_DYNAMIC_STATE_FEATURES_EXT;
	extDynState.extendedDynamicState = VK_TRUE;
	extDynState.pNext = &features13;

	VkDeviceCreateInfo ci = {};
	ci.sType = VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO;
	ci.pNext = &extDynState;
	ci.queueCreateInfoCount = (uint32_t)queueCIs.size();
	ci.pQueueCreateInfos = queueCIs.data();
	ci.enabledExtensionCount = 1;
	ci.ppEnabledExtensionNames = deviceExts;
	ci.pEnabledFeatures = &features;

	if (vkCreateDevice(m_ctx.physicalDevice, &ci, nullptr, &m_ctx.device) != VK_SUCCESS)
		return false;

	vkGetDeviceQueue(m_ctx.device, m_ctx.graphicsQueueFamily, 0, &m_ctx.graphicsQueue);
	vkGetDeviceQueue(m_ctx.device, m_ctx.presentQueueFamily, 0, &m_ctx.presentQueue);
	return true;
}

bool RageDisplay_Vulkan::CreateSwapchain()
{
	VkSurfaceCapabilitiesKHR caps;
	vkGetPhysicalDeviceSurfaceCapabilitiesKHR(m_ctx.physicalDevice, m_ctx.surface, &caps);

	uint32_t formatCount;
	vkGetPhysicalDeviceSurfaceFormatsKHR(m_ctx.physicalDevice, m_ctx.surface, &formatCount, nullptr);
	std::vector<VkSurfaceFormatKHR> formats(formatCount);
	vkGetPhysicalDeviceSurfaceFormatsKHR(m_ctx.physicalDevice, m_ctx.surface, &formatCount, formats.data());

	// Prefer BGRA8 SRGB or UNORM
	VkSurfaceFormatKHR chosen = formats[0];
	for (auto &f : formats)
	{
		if (f.format == VK_FORMAT_B8G8R8A8_UNORM)
		{
			chosen = f;
			break;
		}
	}
	m_ctx.swapchainFormat = chosen.format;

	// Extent
	if (caps.currentExtent.width != UINT32_MAX)
	{
		m_ctx.swapchainExtent = caps.currentExtent;
	}
	else
	{
		auto *pWind = dynamic_cast<LowLevelWindow_SDL *>(g_pWind);
		int w, h;
		SDL_GetWindowSizeInPixels(pWind->GetWindow(), &w, &h);
		m_ctx.swapchainExtent.width = std::clamp((uint32_t)w, caps.minImageExtent.width, caps.maxImageExtent.width);
		m_ctx.swapchainExtent.height = std::clamp((uint32_t)h, caps.minImageExtent.height, caps.maxImageExtent.height);
	}

	uint32_t imageCount = caps.minImageCount + 1;
	if (caps.maxImageCount > 0 && imageCount > caps.maxImageCount)
		imageCount = caps.maxImageCount;

	VkSwapchainKHR oldSwapchain = m_ctx.swapchain;

	VkSwapchainCreateInfoKHR ci = {};
	ci.sType = VK_STRUCTURE_TYPE_SWAPCHAIN_CREATE_INFO_KHR;
	ci.surface = m_ctx.surface;
	ci.minImageCount = imageCount;
	ci.imageFormat = chosen.format;
	ci.imageColorSpace = chosen.colorSpace;
	ci.imageExtent = m_ctx.swapchainExtent;
	ci.imageArrayLayers = 1;
	ci.imageUsage = VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT;
	ci.preTransform = caps.currentTransform;
	ci.compositeAlpha = VK_COMPOSITE_ALPHA_OPAQUE_BIT_KHR;
	// Select present mode based on vsync preference
	VkPresentModeKHR presentMode = VK_PRESENT_MODE_FIFO_KHR; // vsync on (default)
	if (!g_pWind->GetActualVideoModeParams().vsync)
	{
		// Prefer MAILBOX (low-latency, no tearing) over IMMEDIATE (tearing OK)
		uint32_t presentModeCount;
		vkGetPhysicalDeviceSurfacePresentModesKHR(m_ctx.physicalDevice, m_ctx.surface, &presentModeCount, nullptr);
		std::vector<VkPresentModeKHR> presentModes(presentModeCount);
		vkGetPhysicalDeviceSurfacePresentModesKHR(m_ctx.physicalDevice, m_ctx.surface, &presentModeCount, presentModes.data());

		presentMode = VK_PRESENT_MODE_IMMEDIATE_KHR; // fallback: no vsync
		for (auto mode : presentModes)
		{
			if (mode == VK_PRESENT_MODE_MAILBOX_KHR)
			{
				presentMode = VK_PRESENT_MODE_MAILBOX_KHR;
				break;
			}
		}
		LOG->Info("Vulkan: Vsync off, present mode: %s",
			presentMode == VK_PRESENT_MODE_MAILBOX_KHR ? "mailbox" : "immediate");
	}
	ci.presentMode = presentMode;
	ci.clipped = VK_TRUE;
	ci.oldSwapchain = oldSwapchain;

	if (m_ctx.graphicsQueueFamily != m_ctx.presentQueueFamily)
	{
		uint32_t families[] = {m_ctx.graphicsQueueFamily, m_ctx.presentQueueFamily};
		ci.imageSharingMode = VK_SHARING_MODE_CONCURRENT;
		ci.queueFamilyIndexCount = 2;
		ci.pQueueFamilyIndices = families;
	}
	else
	{
		ci.imageSharingMode = VK_SHARING_MODE_EXCLUSIVE;
	}

	if (vkCreateSwapchainKHR(m_ctx.device, &ci, nullptr, &m_ctx.swapchain) != VK_SUCCESS)
		return false;

	if (oldSwapchain)
	{
		// Destroy old swapchain image views
		for (auto &iv : m_ctx.swapchainImageViews)
			vkDestroyImageView(m_ctx.device, iv, nullptr);
		for (auto &fb : m_ctx.framebuffers)
			vkDestroyFramebuffer(m_ctx.device, fb, nullptr);
		vkDestroySwapchainKHR(m_ctx.device, oldSwapchain, nullptr);
	}

	vkGetSwapchainImagesKHR(m_ctx.device, m_ctx.swapchain, &imageCount, nullptr);
	m_ctx.swapchainImages.resize(imageCount);
	vkGetSwapchainImagesKHR(m_ctx.device, m_ctx.swapchain, &imageCount, m_ctx.swapchainImages.data());

	// Create image views
	m_ctx.swapchainImageViews.resize(imageCount);
	for (uint32_t i = 0; i < imageCount; i++)
	{
		VkImageViewCreateInfo viewCI = {};
		viewCI.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
		viewCI.image = m_ctx.swapchainImages[i];
		viewCI.viewType = VK_IMAGE_VIEW_TYPE_2D;
		viewCI.format = m_ctx.swapchainFormat;
		viewCI.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
		vkCreateImageView(m_ctx.device, &viewCI, nullptr, &m_ctx.swapchainImageViews[i]);
	}

	LOG->Info("Vulkan: Swapchain %ux%u, %u images", m_ctx.swapchainExtent.width, m_ctx.swapchainExtent.height, imageCount);
	return true;
}

void RageDisplay_Vulkan::DestroySwapchain()
{
	for (auto &fb : m_ctx.framebuffers)
		if (fb) vkDestroyFramebuffer(m_ctx.device, fb, nullptr);
	m_ctx.framebuffers.clear();

	for (auto &iv : m_ctx.swapchainImageViews)
		if (iv) vkDestroyImageView(m_ctx.device, iv, nullptr);
	m_ctx.swapchainImageViews.clear();

	if (m_ctx.depthImageView) { vkDestroyImageView(m_ctx.device, m_ctx.depthImageView, nullptr); m_ctx.depthImageView = VK_NULL_HANDLE; }
	if (m_ctx.depthImage) { vmaDestroyImage(m_ctx.allocator, m_ctx.depthImage, m_ctx.depthAllocation); m_ctx.depthImage = VK_NULL_HANDLE; }

	if (m_ctx.swapchain) { vkDestroySwapchainKHR(m_ctx.device, m_ctx.swapchain, nullptr); m_ctx.swapchain = VK_NULL_HANDLE; }
}

bool RageDisplay_Vulkan::CreateRenderPass()
{
	VkAttachmentDescription colorAttach = {};
	colorAttach.format = m_ctx.swapchainFormat;
	colorAttach.samples = VK_SAMPLE_COUNT_1_BIT;
	colorAttach.loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
	colorAttach.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
	colorAttach.stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
	colorAttach.stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
	colorAttach.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
	colorAttach.finalLayout = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR;

	VkAttachmentDescription depthAttach = {};
	depthAttach.format = VK_FORMAT_D16_UNORM;
	depthAttach.samples = VK_SAMPLE_COUNT_1_BIT;
	depthAttach.loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
	depthAttach.storeOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
	depthAttach.stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
	depthAttach.stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
	depthAttach.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
	depthAttach.finalLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;

	VkAttachmentReference colorRef = {0, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL};
	VkAttachmentReference depthRef = {1, VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL};

	VkSubpassDescription subpass = {};
	subpass.pipelineBindPoint = VK_PIPELINE_BIND_POINT_GRAPHICS;
	subpass.colorAttachmentCount = 1;
	subpass.pColorAttachments = &colorRef;
	subpass.pDepthStencilAttachment = &depthRef;

	VkSubpassDependency dep = {};
	dep.srcSubpass = VK_SUBPASS_EXTERNAL;
	dep.dstSubpass = 0;
	dep.srcStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT | VK_PIPELINE_STAGE_EARLY_FRAGMENT_TESTS_BIT;
	dep.dstStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT | VK_PIPELINE_STAGE_EARLY_FRAGMENT_TESTS_BIT;
	dep.srcAccessMask = 0;
	dep.dstAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT | VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT;

	VkAttachmentDescription attachments[] = {colorAttach, depthAttach};

	VkRenderPassCreateInfo rpCI = {};
	rpCI.sType = VK_STRUCTURE_TYPE_RENDER_PASS_CREATE_INFO;
	rpCI.attachmentCount = 2;
	rpCI.pAttachments = attachments;
	rpCI.subpassCount = 1;
	rpCI.pSubpasses = &subpass;
	rpCI.dependencyCount = 1;
	rpCI.pDependencies = &dep;

	return vkCreateRenderPass(m_ctx.device, &rpCI, nullptr, &m_ctx.renderPass) == VK_SUCCESS;
}

bool RageDisplay_Vulkan::CreateDepthBuffer()
{
	// Destroy old if exists
	if (m_ctx.depthImageView) { vkDestroyImageView(m_ctx.device, m_ctx.depthImageView, nullptr); m_ctx.depthImageView = VK_NULL_HANDLE; }
	if (m_ctx.depthImage) { vmaDestroyImage(m_ctx.allocator, m_ctx.depthImage, m_ctx.depthAllocation); m_ctx.depthImage = VK_NULL_HANDLE; }

	VkImageCreateInfo imgCI = {};
	imgCI.sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO;
	imgCI.imageType = VK_IMAGE_TYPE_2D;
	imgCI.format = m_ctx.depthFormat;
	imgCI.extent = {m_ctx.swapchainExtent.width, m_ctx.swapchainExtent.height, 1};
	imgCI.mipLevels = 1;
	imgCI.arrayLayers = 1;
	imgCI.samples = VK_SAMPLE_COUNT_1_BIT;
	imgCI.tiling = VK_IMAGE_TILING_OPTIMAL;
	imgCI.usage = VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT;

	VmaAllocationCreateInfo allocCI = {};
	allocCI.usage = VMA_MEMORY_USAGE_AUTO;
	if (vmaCreateImage(m_ctx.allocator, &imgCI, &allocCI, &m_ctx.depthImage, &m_ctx.depthAllocation, nullptr) != VK_SUCCESS)
		return false;

	VkImageViewCreateInfo viewCI = {};
	viewCI.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
	viewCI.image = m_ctx.depthImage;
	viewCI.viewType = VK_IMAGE_VIEW_TYPE_2D;
	viewCI.format = m_ctx.depthFormat;
	viewCI.subresourceRange = {VK_IMAGE_ASPECT_DEPTH_BIT, 0, 1, 0, 1};
	return vkCreateImageView(m_ctx.device, &viewCI, nullptr, &m_ctx.depthImageView) == VK_SUCCESS;
}

bool RageDisplay_Vulkan::CreateFramebuffers()
{
	m_ctx.framebuffers.resize(m_ctx.swapchainImageViews.size());
	for (size_t i = 0; i < m_ctx.swapchainImageViews.size(); i++)
	{
		VkImageView attachments[] = {m_ctx.swapchainImageViews[i], m_ctx.depthImageView};

		VkFramebufferCreateInfo fbCI = {};
		fbCI.sType = VK_STRUCTURE_TYPE_FRAMEBUFFER_CREATE_INFO;
		fbCI.renderPass = m_ctx.renderPass;
		fbCI.attachmentCount = 2;
		fbCI.pAttachments = attachments;
		fbCI.width = m_ctx.swapchainExtent.width;
		fbCI.height = m_ctx.swapchainExtent.height;
		fbCI.layers = 1;

		if (vkCreateFramebuffer(m_ctx.device, &fbCI, nullptr, &m_ctx.framebuffers[i]) != VK_SUCCESS)
			return false;
	}
	return true;
}

bool RageDisplay_Vulkan::CreateFrameResources()
{
	for (int i = 0; i < VulkanContext::MAX_FRAMES_IN_FLIGHT; i++)
	{
		auto &f = m_ctx.frames[i];

		// Command pool
		VkCommandPoolCreateInfo poolCI = {};
		poolCI.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
		poolCI.queueFamilyIndex = m_ctx.graphicsQueueFamily;
		poolCI.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
		vkCreateCommandPool(m_ctx.device, &poolCI, nullptr, &f.commandPool);

		// Command buffer
		VkCommandBufferAllocateInfo cmdAI = {};
		cmdAI.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
		cmdAI.commandPool = f.commandPool;
		cmdAI.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
		cmdAI.commandBufferCount = 1;
		vkAllocateCommandBuffers(m_ctx.device, &cmdAI, &f.commandBuffer);

		// Sync objects
		VkSemaphoreCreateInfo semCI = {};
		semCI.sType = VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO;
		vkCreateSemaphore(m_ctx.device, &semCI, nullptr, &f.imageAvailable);
		vkCreateSemaphore(m_ctx.device, &semCI, nullptr, &f.renderFinished);

		VkFenceCreateInfo fenceCI = {};
		fenceCI.sType = VK_STRUCTURE_TYPE_FENCE_CREATE_INFO;
		fenceCI.flags = VK_FENCE_CREATE_SIGNALED_BIT;
		vkCreateFence(m_ctx.device, &fenceCI, nullptr, &f.inFlight);

		// Streaming vertex buffer
		f.vertexCapacity = VERTEX_RING_SIZE;
		VkBufferCreateInfo bufCI = {};
		bufCI.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
		bufCI.size = f.vertexCapacity;
		bufCI.usage = VK_BUFFER_USAGE_VERTEX_BUFFER_BIT;

		VmaAllocationCreateInfo allocCI = {};
		allocCI.usage = VMA_MEMORY_USAGE_AUTO;
		allocCI.flags = VMA_ALLOCATION_CREATE_HOST_ACCESS_SEQUENTIAL_WRITE_BIT | VMA_ALLOCATION_CREATE_MAPPED_BIT;

		VmaAllocationInfo allocInfo;
		vmaCreateBuffer(m_ctx.allocator, &bufCI, &allocCI, &f.vertexBuffer, &f.vertexAllocation, &allocInfo);
		f.vertexMapped = allocInfo.pMappedData;

		// Staging buffer
		f.stagingCapacity = STAGING_RING_SIZE;
		bufCI.size = f.stagingCapacity;
		bufCI.usage = VK_BUFFER_USAGE_TRANSFER_SRC_BIT;
		vmaCreateBuffer(m_ctx.allocator, &bufCI, &allocCI, &f.stagingBuffer, &f.stagingAllocation, &allocInfo);
		f.stagingMapped = allocInfo.pMappedData;

		// Descriptor pool
		VkDescriptorPoolSize poolSizes[] = {
			{VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 512},
			{VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER_DYNAMIC, 16},
		};
		VkDescriptorPoolCreateInfo dpCI = {};
		dpCI.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO;
		dpCI.maxSets = 512;
		dpCI.poolSizeCount = 2;
		dpCI.pPoolSizes = poolSizes;
		vkCreateDescriptorPool(m_ctx.device, &dpCI, nullptr, &f.descriptorPool);
	}
	return true;
}

void RageDisplay_Vulkan::DestroyFrameResources()
{
	for (int i = 0; i < VulkanContext::MAX_FRAMES_IN_FLIGHT; i++)
	{
		auto &f = m_ctx.frames[i];
		if (f.inFlight) vkDestroyFence(m_ctx.device, f.inFlight, nullptr);
		if (f.renderFinished) vkDestroySemaphore(m_ctx.device, f.renderFinished, nullptr);
		if (f.imageAvailable) vkDestroySemaphore(m_ctx.device, f.imageAvailable, nullptr);
		if (f.commandPool) vkDestroyCommandPool(m_ctx.device, f.commandPool, nullptr);
		if (f.vertexBuffer) vmaDestroyBuffer(m_ctx.allocator, f.vertexBuffer, f.vertexAllocation);
		if (f.stagingBuffer) vmaDestroyBuffer(m_ctx.allocator, f.stagingBuffer, f.stagingAllocation);
		if (f.descriptorPool) vkDestroyDescriptorPool(m_ctx.device, f.descriptorPool, nullptr);
	}
}

bool RageDisplay_Vulkan::CreatePipelineLayout()
{
	// Set 0: per-frame UBO (lighting/material)
	{
		VkDescriptorSetLayoutBinding uboBinding = {};
		uboBinding.binding = 0;
		uboBinding.descriptorType = VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER_DYNAMIC;
		uboBinding.descriptorCount = 1;
		uboBinding.stageFlags = VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT;

		VkDescriptorSetLayoutCreateInfo ci = {};
		ci.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
		ci.bindingCount = 1;
		ci.pBindings = &uboBinding;
		vkCreateDescriptorSetLayout(m_ctx.device, &ci, nullptr, &m_descSetLayoutPerFrame);
	}

	// Set 1: texture sampler
	{
		VkDescriptorSetLayoutBinding texBinding = {};
		texBinding.binding = 0;
		texBinding.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
		texBinding.descriptorCount = 1;
		texBinding.stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;

		VkDescriptorSetLayoutCreateInfo ci = {};
		ci.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
		ci.bindingCount = 1;
		ci.pBindings = &texBinding;
		vkCreateDescriptorSetLayout(m_ctx.device, &ci, nullptr, &m_descSetLayoutTexture);
	}

	VkDescriptorSetLayout layouts[] = {m_descSetLayoutPerFrame, m_descSetLayoutTexture};

	VkPushConstantRange pcRange = {};
	pcRange.stageFlags = VK_SHADER_STAGE_VERTEX_BIT;
	pcRange.offset = 0;
	pcRange.size = 128; // 2x mat4

	VkPipelineLayoutCreateInfo ci = {};
	ci.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
	ci.setLayoutCount = 2;
	ci.pSetLayouts = layouts;
	ci.pushConstantRangeCount = 1;
	ci.pPushConstantRanges = &pcRange;

	return vkCreatePipelineLayout(m_ctx.device, &ci, nullptr, &m_pipelineLayout) == VK_SUCCESS;
}

