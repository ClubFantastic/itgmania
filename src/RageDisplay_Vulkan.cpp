std::string RageDisplay_Vulkan::Init(const VideoModeParams &p, bool bAllowUnacceleratedRenderer)
{
	LOG->Info("RageDisplay_Vulkan::Init()");

	// Tell LLW_SDL to create a Vulkan window
	LowLevelWindow_SDL::SetWindowAPI(LowLevelWindow_SDL::WindowAPI::Vulkan);

	g_pWind = LowLevelWindow::Create();
	if (!g_pWind)
		return "Failed to create LowLevelWindow";

	bool bNewDeviceOut;
	std::string sErr = TryVideoMode(p, bNewDeviceOut);
	if (!sErr.empty())
		return sErr;

	return std::string();
}

std::string RageDisplay_Vulkan::TryVideoMode(const VideoModeParams &p, bool &bNewDeviceOut)
{
	bNewDeviceOut = (m_ctx.device == VK_NULL_HANDLE);

	// Create or resize the SDL window
	g_pWind->TryVideoMode(p, bNewDeviceOut);

	if (m_ctx.device == VK_NULL_HANDLE)
	{
		// First-time init
		if (!CreateInstance()) return "Failed to create Vulkan instance";
		if (!SelectPhysicalDevice()) return "No suitable Vulkan GPU found";
		if (!CreateLogicalDevice()) return "Failed to create Vulkan device";

		// Create VMA allocator
		VmaVulkanFunctions vulkanFunctions = {};
		vulkanFunctions.vkGetInstanceProcAddr = vkGetInstanceProcAddr;
		vulkanFunctions.vkGetDeviceProcAddr = vkGetDeviceProcAddr;

		VmaAllocatorCreateInfo allocatorCI = {};
		allocatorCI.physicalDevice = m_ctx.physicalDevice;
		allocatorCI.device = m_ctx.device;
		allocatorCI.instance = m_ctx.instance;
		allocatorCI.pVulkanFunctions = &vulkanFunctions;
		if (vmaCreateAllocator(&allocatorCI, &m_ctx.allocator) != VK_SUCCESS)
			return "Failed to create VMA allocator";

		if (!CreateRenderPass()) return "Failed to create render pass";
		if (!CreatePipelineLayout()) return "Failed to create pipeline layout";
		if (!CreateShaderModules()) return "Failed to load shaders";
		if (!CreateSamplers()) return "Failed to create samplers";

		// Create a 4-byte white color buffer for model rendering (models
		// have no per-vertex color, so we bind this as a constant).
		{
			uint32_t white = 0xFFFFFFFF;
			VkBufferCreateInfo bufCI = {};
			bufCI.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
			bufCI.size = 4;
			bufCI.usage = VK_BUFFER_USAGE_VERTEX_BUFFER_BIT;
			VmaAllocationCreateInfo allocCI = {};
			allocCI.usage = VMA_MEMORY_USAGE_AUTO;
			allocCI.flags = VMA_ALLOCATION_CREATE_HOST_ACCESS_SEQUENTIAL_WRITE_BIT;
			vmaCreateBuffer(m_ctx.allocator, &bufCI, &allocCI, &m_whiteColorBuf, &m_whiteColorAlloc, nullptr);
			void *mapped;
			vmaMapMemory(m_ctx.allocator, m_whiteColorAlloc, &mapped);
			memcpy(mapped, &white, 4);
			vmaUnmapMemory(m_ctx.allocator, m_whiteColorAlloc);
		}
		if (!CreateFrameResources()) return "Failed to create frame resources";

		// Create pipeline cache
		VkPipelineCacheCreateInfo cacheCI = {};
		cacheCI.sType = VK_STRUCTURE_TYPE_PIPELINE_CACHE_CREATE_INFO;
		vkCreatePipelineCache(m_ctx.device, &cacheCI, nullptr, &m_vkPipelineCache);

		// Create dummy white texture
		{
			uint32_t white = 0xFFFFFFFF;
			VkImageCreateInfo imgCI = {};
			imgCI.sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO;
			imgCI.imageType = VK_IMAGE_TYPE_2D;
			imgCI.format = VK_FORMAT_R8G8B8A8_UNORM;
			imgCI.extent = {1, 1, 1};
			imgCI.mipLevels = 1;
			imgCI.arrayLayers = 1;
			imgCI.samples = VK_SAMPLE_COUNT_1_BIT;
			imgCI.tiling = VK_IMAGE_TILING_OPTIMAL;
			imgCI.usage = VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_SAMPLED_BIT;

			VmaAllocationCreateInfo allocCI = {};
			allocCI.usage = VMA_MEMORY_USAGE_AUTO;
			vmaCreateImage(m_ctx.allocator, &imgCI, &allocCI, &m_dummyTexture.image, &m_dummyTexture.allocation, nullptr);

			VkImageViewCreateInfo viewCI = {};
			viewCI.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
			viewCI.image = m_dummyTexture.image;
			viewCI.viewType = VK_IMAGE_VIEW_TYPE_2D;
			viewCI.format = VK_FORMAT_R8G8B8A8_UNORM;
			viewCI.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
			vkCreateImageView(m_ctx.device, &viewCI, nullptr, &m_dummyTexture.imageView);

			m_dummyTexture.width = 1;
			m_dummyTexture.height = 1;
			m_dummyTexture.format = VK_FORMAT_R8G8B8A8_UNORM;

			// Upload the white pixel via an immediate command
			VkCommandPool tempPool;
			VkCommandPoolCreateInfo poolCI = {};
			poolCI.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
			poolCI.queueFamilyIndex = m_ctx.graphicsQueueFamily;
			poolCI.flags = VK_COMMAND_POOL_CREATE_TRANSIENT_BIT;
			vkCreateCommandPool(m_ctx.device, &poolCI, nullptr, &tempPool);

			VkCommandBufferAllocateInfo cmdAI = {};
			cmdAI.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
			cmdAI.commandPool = tempPool;
			cmdAI.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
			cmdAI.commandBufferCount = 1;
			VkCommandBuffer tempCmd;
			vkAllocateCommandBuffers(m_ctx.device, &cmdAI, &tempCmd);

			VkCommandBufferBeginInfo beginInfo = {};
			beginInfo.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
			beginInfo.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
			vkBeginCommandBuffer(tempCmd, &beginInfo);

			// Create tiny staging buffer
			VkBuffer stagingBuf;
			VmaAllocation stagingAlloc;
			VkBufferCreateInfo bufCI = {};
			bufCI.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
			bufCI.size = 4;
			bufCI.usage = VK_BUFFER_USAGE_TRANSFER_SRC_BIT;
			VmaAllocationCreateInfo stagingAllocCI = {};
			stagingAllocCI.usage = VMA_MEMORY_USAGE_AUTO;
			stagingAllocCI.flags = VMA_ALLOCATION_CREATE_HOST_ACCESS_SEQUENTIAL_WRITE_BIT;
			vmaCreateBuffer(m_ctx.allocator, &bufCI, &stagingAllocCI, &stagingBuf, &stagingAlloc, nullptr);
			void *mapped;
			vmaMapMemory(m_ctx.allocator, stagingAlloc, &mapped);
			memcpy(mapped, &white, 4);
			vmaUnmapMemory(m_ctx.allocator, stagingAlloc);

			VulkanUtil::TransitionImageLayout(tempCmd, m_dummyTexture.image,
				VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL);

			VkBufferImageCopy region = {};
			region.imageSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
			region.imageExtent = {1, 1, 1};
			vkCmdCopyBufferToImage(tempCmd, stagingBuf, m_dummyTexture.image,
				VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &region);

			VulkanUtil::TransitionImageLayout(tempCmd, m_dummyTexture.image,
				VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);

			vkEndCommandBuffer(tempCmd);

			VkSubmitInfo submitInfo = {};
			submitInfo.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
			submitInfo.commandBufferCount = 1;
			submitInfo.pCommandBuffers = &tempCmd;
			vkQueueSubmit(m_ctx.graphicsQueue, 1, &submitInfo, VK_NULL_HANDLE);
			vkQueueWaitIdle(m_ctx.graphicsQueue);

			vmaDestroyBuffer(m_ctx.allocator, stagingBuf, stagingAlloc);
			vkDestroyCommandPool(m_ctx.device, tempPool, nullptr);
		}

		// Create UBO ring buffer for lighting data
		{
			VkPhysicalDeviceProperties props;
			vkGetPhysicalDeviceProperties(m_ctx.physicalDevice, &props);
			m_uboAlignment = std::max((uint32_t)sizeof(PerFrameUBOData),
				(uint32_t)props.limits.minUniformBufferOffsetAlignment);
			// Round up to alignment
			m_uboAlignment = (m_uboAlignment + (uint32_t)props.limits.minUniformBufferOffsetAlignment - 1)
				& ~((uint32_t)props.limits.minUniformBufferOffsetAlignment - 1);

			VkBufferCreateInfo bufCI = {};
			bufCI.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
			bufCI.size = m_uboAlignment * UBO_RING_SIZE * VulkanContext::MAX_FRAMES_IN_FLIGHT;
			bufCI.usage = VK_BUFFER_USAGE_UNIFORM_BUFFER_BIT;

			VmaAllocationCreateInfo allocCI = {};
			allocCI.usage = VMA_MEMORY_USAGE_AUTO;
			allocCI.flags = VMA_ALLOCATION_CREATE_HOST_ACCESS_SEQUENTIAL_WRITE_BIT |
			                VMA_ALLOCATION_CREATE_MAPPED_BIT;

			VmaAllocationInfo allocInfo;
			vmaCreateBuffer(m_ctx.allocator, &bufCI, &allocCI, &m_uboBuffer, &m_uboAlloc, &allocInfo);
			m_uboMapped = allocInfo.pMappedData;
		}
	}

	// (Re)create swapchain
	if (!CreateSwapchain()) return "Failed to create swapchain";
	if (!CreateDepthBuffer()) return "Failed to create depth buffer";
	if (!CreateFramebuffers()) return "Failed to create framebuffers";

	return std::string();
}

