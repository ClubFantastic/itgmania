bool RageDisplay_Vulkan::CreateSamplers()
{
	for (int wrap = 0; wrap < 2; wrap++)
	{
		for (int linear = 0; linear < 2; linear++)
		{
			VkSamplerCreateInfo ci = {};
			ci.sType = VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO;
			ci.magFilter = linear ? VK_FILTER_LINEAR : VK_FILTER_NEAREST;
			ci.minFilter = linear ? VK_FILTER_LINEAR : VK_FILTER_NEAREST;
			ci.mipmapMode = linear ? VK_SAMPLER_MIPMAP_MODE_LINEAR : VK_SAMPLER_MIPMAP_MODE_NEAREST;
			ci.addressModeU = wrap ? VK_SAMPLER_ADDRESS_MODE_REPEAT : VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
			ci.addressModeV = wrap ? VK_SAMPLER_ADDRESS_MODE_REPEAT : VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
			ci.addressModeW = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
			ci.maxLod = VK_LOD_CLAMP_NONE;

			if (vkCreateSampler(m_ctx.device, &ci, nullptr, &m_samplers[wrap * 2 + linear]) != VK_SUCCESS)
				return false;
		}
	}
	return true;
}

VkSampler RageDisplay_Vulkan::GetSampler(bool wrap, bool linear) const
{
	return m_samplers[(wrap ? 1 : 0) * 2 + (linear ? 1 : 0)];
}

