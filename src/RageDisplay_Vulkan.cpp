uintptr_t RageDisplay_Vulkan::CreateTexture(RagePixelFormat pixfmt, RageSurface *img, bool bGenerateMipMaps)
{
	int texW = vk_power_of_two(img->w);
	int texH = vk_power_of_two(img->h);

	// All textures stored as VK_FORMAT_B8G8R8A8_UNORM (byte order: B,G,R,A).
	// UpdateTexture blits into a staging surface with matching masks.
	(void)pixfmt;
	VkFormat format = VK_FORMAT_B8G8R8A8_UNORM;

	VkImageCreateInfo imgCI = {};
	imgCI.sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO;
	imgCI.imageType = VK_IMAGE_TYPE_2D;
	imgCI.format = format;
	imgCI.extent = {(uint32_t)texW, (uint32_t)texH, 1};
	imgCI.mipLevels = 1;
	imgCI.arrayLayers = 1;
	imgCI.samples = VK_SAMPLE_COUNT_1_BIT;
	imgCI.tiling = VK_IMAGE_TILING_OPTIMAL;
	imgCI.usage = VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_SAMPLED_BIT;

	VmaAllocationCreateInfo allocCI = {};
	allocCI.usage = VMA_MEMORY_USAGE_AUTO;

	VulkanTexture tex;
	tex.format = format;
	tex.width = texW;
	tex.height = texH;
	tex.hasMipmaps = bGenerateMipMaps;

	if (vmaCreateImage(m_ctx.allocator, &imgCI, &allocCI, &tex.image, &tex.allocation, nullptr) != VK_SUCCESS)
	{
		LOG->Warn("Vulkan: Failed to create texture image %dx%d", texW, texH);
		return 0;
	}

	VkImageViewCreateInfo viewCI = {};
	viewCI.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
	viewCI.image = tex.image;
	viewCI.viewType = VK_IMAGE_VIEW_TYPE_2D;
	viewCI.format = format;
	viewCI.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
	vkCreateImageView(m_ctx.device, &viewCI, nullptr, &tex.imageView);

	uintptr_t handle = AllocTextureHandle();
	m_textures[handle] = tex;

	// Upload pixel data
	if (img->pixels)
		UpdateTexture(handle, img, 0, 0, img->w, img->h);

	return handle;
}

void RageDisplay_Vulkan::UpdateTexture(uintptr_t iTexHandle, RageSurface *img,
	int xoffset, int yoffset, int width, int height)
{
	auto it = m_textures.find(iTexHandle);
	if (it == m_textures.end()) return;

	auto &tex = it->second;
	uint32_t uploadSize = width * height * 4;

	// Create a staging buffer for this upload
	VkBuffer stagingBuf;
	VmaAllocation stagingAlloc;
	VkBufferCreateInfo bufCI = {};
	bufCI.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
	bufCI.size = uploadSize;
	bufCI.usage = VK_BUFFER_USAGE_TRANSFER_SRC_BIT;

	VmaAllocationCreateInfo stagingAllocCI = {};
	stagingAllocCI.usage = VMA_MEMORY_USAGE_AUTO;
	stagingAllocCI.flags = VMA_ALLOCATION_CREATE_HOST_ACCESS_SEQUENTIAL_WRITE_BIT |
	                       VMA_ALLOCATION_CREATE_MAPPED_BIT;

	VmaAllocationInfo allocInfo;
	vmaCreateBuffer(m_ctx.allocator, &bufCI, &stagingAllocCI, &stagingBuf, &stagingAlloc, &allocInfo);

	// Create staging surface matching VK_FORMAT_B8G8R8A8_UNORM byte order.
	// On little-endian: byte[0]=B, byte[1]=G, byte[2]=R, byte[3]=A
	// Masks: R=0x00FF0000, G=0x0000FF00, B=0x000000FF, A=0xFF000000
	// Pre-fill with alpha=0xFF so RGB sources without alpha get opaque pixels.
	memset(allocInfo.pMappedData, 0xFF, uploadSize);
	RageSurface *staging = CreateSurfaceFrom(
		width, height, 32,
		0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000,
		(uint8_t *)allocInfo.pMappedData, width * 4);
	if (staging)
	{
		RageSurfaceUtils::Blit(img, staging, width, height);
		delete staging;
	}

	// Batch into the pending upload command buffer
	if (!m_uploadCmd)
	{
		// Create a reusable command pool if needed
		if (!m_uploadPool)
		{
			VkCommandPoolCreateInfo poolCI = {};
			poolCI.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
			poolCI.queueFamilyIndex = m_ctx.graphicsQueueFamily;
			poolCI.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
			vkCreateCommandPool(m_ctx.device, &poolCI, nullptr, &m_uploadPool);

			VkCommandBufferAllocateInfo cmdAI = {};
			cmdAI.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
			cmdAI.commandPool = m_uploadPool;
			cmdAI.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
			cmdAI.commandBufferCount = 1;
			vkAllocateCommandBuffers(m_ctx.device, &cmdAI, &m_uploadCmdBuf);

			VkFenceCreateInfo fenceCI = {};
			fenceCI.sType = VK_STRUCTURE_TYPE_FENCE_CREATE_INFO;
			vkCreateFence(m_ctx.device, &fenceCI, nullptr, &m_uploadFence);
		}

		// Begin recording
		vkResetCommandBuffer(m_uploadCmdBuf, 0);
		VkCommandBufferBeginInfo beginInfo = {};
		beginInfo.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
		beginInfo.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
		vkBeginCommandBuffer(m_uploadCmdBuf, &beginInfo);
		m_uploadCmd = true;
	}

	VulkanUtil::TransitionImageLayout(m_uploadCmdBuf, tex.image,
		VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL);

	VkBufferImageCopy region = {};
	region.bufferOffset = 0;
	region.imageSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
	region.imageOffset = {xoffset, yoffset, 0};
	region.imageExtent = {(uint32_t)width, (uint32_t)height, 1};

	vkCmdCopyBufferToImage(m_uploadCmdBuf, stagingBuf, tex.image,
		VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &region);

	VulkanUtil::TransitionImageLayout(m_uploadCmdBuf, tex.image,
		VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);

	// Track staging buffer for cleanup after flush
	m_pendingStagingBuffers.push_back({stagingBuf, stagingAlloc});

	// Always flush immediately — the engine expects textures to be usable
	// right after CreateTexture/UpdateTexture returns
	FlushTextureUploads();
}

void RageDisplay_Vulkan::FlushTextureUploads()
{
	if (!m_uploadCmd || m_pendingStagingBuffers.empty())
		return;

	vkEndCommandBuffer(m_uploadCmdBuf);

	vkResetFences(m_ctx.device, 1, &m_uploadFence);

	VkSubmitInfo submitInfo = {};
	submitInfo.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
	submitInfo.commandBufferCount = 1;
	submitInfo.pCommandBuffers = &m_uploadCmdBuf;
	vkQueueSubmit(m_ctx.graphicsQueue, 1, &submitInfo, m_uploadFence);
	vkWaitForFences(m_ctx.device, 1, &m_uploadFence, VK_TRUE, UINT64_MAX);

	// Clean up staging buffers
	for (auto &[buf, alloc] : m_pendingStagingBuffers)
		vmaDestroyBuffer(m_ctx.allocator, buf, alloc);
	m_pendingStagingBuffers.clear();

	m_uploadCmd = false;
}

void RageDisplay_Vulkan::DeleteTexture(uintptr_t iTexHandle)
{
	auto it = m_textures.find(iTexHandle);
	if (it == m_textures.end()) return;

	// Flush pending uploads that might reference this texture
	FlushTextureUploads();
	vkDeviceWaitIdle(m_ctx.device);

	auto &tex = it->second;
	if (tex.imageView) vkDestroyImageView(m_ctx.device, tex.imageView, nullptr);
	if (tex.image) vmaDestroyImage(m_ctx.allocator, tex.image, tex.allocation);
	m_textures.erase(it);
}

