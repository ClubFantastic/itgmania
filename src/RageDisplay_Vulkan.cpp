uint16_t RageDisplay_Vulkan::GetCurrentShaderVariant() const
{
	// Encode: vertex shader (0=sprite, 1=lit) | fragment shader selection | spec constants
	uint16_t variant = 0;

	if (m_bLightingEnabled)
		variant |= (1 << 0); // lit vertex shader

	if (m_curEffectMode != EffectMode_Normal)
	{
		variant |= ((uint16_t)m_curEffectMode << 1); // effect frag (bits 1-4)
		variant |= (1 << 5); // flag: using effect shader
	}
	else
	{
		// Sprite frag specialization constants
		variant |= ((uint16_t)m_curTextureMode << 6);  // bits 6-7
		variant |= (m_bAlphaTestEnabled ? 1 : 0) << 8; // bit 8
		variant |= (m_bTextureEnabled[TextureUnit_1] ? 1 : 0) << 9; // bit 9
	}

	return variant;
}

VulkanPipelineKey RageDisplay_Vulkan::MakeCurrentPipelineKey() const
{
	VulkanPipelineKey key;
	key.shaderVariant = GetCurrentShaderVariant();
	key.blendMode = (uint8_t)m_curBlendMode;
	key.flags = (m_curPolygonMode == POLYGON_LINE ? 1 : 0)
	          | (m_bDrawingModel ? 2 : 0);
	return key;
}

VkPipeline RageDisplay_Vulkan::GetOrCreatePipeline(const VulkanPipelineKey &key)
{
	auto it = m_pipelineCache.find(key);
	if (it != m_pipelineCache.end())
		return it->second;

	// Build pipeline
	bool isLit = (key.shaderVariant & 1);
	bool isEffect = (key.shaderVariant & (1 << 5));

	VkShaderModule vertModule = isLit ? m_litSpriteVert : m_spriteVert;
	VkShaderModule fragModule;

	if (isEffect)
	{
		int effectIdx = (key.shaderVariant >> 1) & 0xF;
		fragModule = m_effectFrags[effectIdx];
		if (!fragModule) fragModule = m_spriteFrag; // fallback
	}
	else if (isLit)
	{
		fragModule = m_litSpriteFrag;
	}
	else
	{
		fragModule = m_spriteFrag;
	}

	// Specialization constants for sprite frag
	struct SpecData { int32_t textureMode; VkBool32 alphaTest; VkBool32 textureEnabled; VkBool32 lightingEnabled; };
	SpecData specData = {};
	specData.textureMode = (key.shaderVariant >> 6) & 0x3;
	specData.alphaTest = (key.shaderVariant >> 8) & 1;
	specData.textureEnabled = (key.shaderVariant >> 9) & 1;
	specData.lightingEnabled = isLit ? VK_TRUE : VK_FALSE;

	VkSpecializationMapEntry specEntries[] = {
		{0, offsetof(SpecData, textureMode), sizeof(int32_t)},
		{1, offsetof(SpecData, alphaTest), sizeof(VkBool32)},
		{2, offsetof(SpecData, textureEnabled), sizeof(VkBool32)},
		{3, offsetof(SpecData, lightingEnabled), sizeof(VkBool32)},
	};

	VkSpecializationInfo specInfo = {};
	specInfo.mapEntryCount = isLit ? 4 : 3;
	specInfo.pMapEntries = specEntries;
	specInfo.dataSize = sizeof(SpecData);
	specInfo.pData = &specData;

	VkPipelineShaderStageCreateInfo stages[2] = {};
	stages[0].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
	stages[0].stage = VK_SHADER_STAGE_VERTEX_BIT;
	stages[0].module = vertModule;
	stages[0].pName = "main";

	stages[1].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
	stages[1].stage = VK_SHADER_STAGE_FRAGMENT_BIT;
	stages[1].module = fragModule;
	stages[1].pName = "main";
	stages[1].pSpecializationInfo = &specInfo;

	// Vertex input layout depends on whether we're drawing sprites or models
	bool isModelFormat = (key.flags & 2);

	// Sprite: single interleaved buffer (pos, normal, color, texcoord)
	VkVertexInputBindingDescription spriteBinding = {};
	spriteBinding.binding = 0;
	spriteBinding.stride = sizeof(RageSpriteVertex);
	spriteBinding.inputRate = VK_VERTEX_INPUT_RATE_VERTEX;

	VkVertexInputAttributeDescription spriteAttrs[4] = {};
	spriteAttrs[0] = {0, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(RageSpriteVertex, p)};
	spriteAttrs[1] = {1, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(RageSpriteVertex, n)};
	spriteAttrs[2] = {2, 0, VK_FORMAT_R8G8B8A8_UNORM, offsetof(RageSpriteVertex, c)};
	spriteAttrs[3] = {3, 0, VK_FORMAT_R32G32_SFLOAT, offsetof(RageSpriteVertex, t)};

	// Model: separate buffers per attribute (pos, normal, texcoord, constant color)
	VkVertexInputBindingDescription modelBindings[4] = {};
	modelBindings[0] = {0, sizeof(RageVector3), VK_VERTEX_INPUT_RATE_VERTEX};    // position
	modelBindings[1] = {1, sizeof(RageVector3), VK_VERTEX_INPUT_RATE_VERTEX};    // normal
	modelBindings[2] = {2, sizeof(RageVector2), VK_VERTEX_INPUT_RATE_VERTEX};    // texcoord
	modelBindings[3] = {3, 0, VK_VERTEX_INPUT_RATE_INSTANCE};                    // constant white color (stride 0 = same value for all)

	VkVertexInputAttributeDescription modelAttrs[4] = {};
	modelAttrs[0] = {0, 0, VK_FORMAT_R32G32B32_SFLOAT, 0};  // position
	modelAttrs[1] = {1, 1, VK_FORMAT_R32G32B32_SFLOAT, 0};  // normal
	modelAttrs[2] = {2, 3, VK_FORMAT_R8G8B8A8_UNORM, 0};    // color (location 2, binding 3 = white buffer)
	modelAttrs[3] = {3, 2, VK_FORMAT_R32G32_SFLOAT, 0};      // texcoord (location 3)

	VkPipelineVertexInputStateCreateInfo vertexInput = {};
	vertexInput.sType = VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO;
	if (isModelFormat)
	{
		vertexInput.vertexBindingDescriptionCount = 4;
		vertexInput.pVertexBindingDescriptions = modelBindings;
		vertexInput.vertexAttributeDescriptionCount = 4;
		vertexInput.pVertexAttributeDescriptions = modelAttrs;
	}
	else
	{
		vertexInput.vertexBindingDescriptionCount = 1;
		vertexInput.pVertexBindingDescriptions = &spriteBinding;
		vertexInput.vertexAttributeDescriptionCount = 4;
		vertexInput.pVertexAttributeDescriptions = spriteAttrs;
	}

	VkPipelineInputAssemblyStateCreateInfo inputAssembly = {};
	inputAssembly.sType = VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO;
	inputAssembly.topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;

	VkPipelineViewportStateCreateInfo viewportState = {};
	viewportState.sType = VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO;
	viewportState.viewportCount = 1;
	viewportState.scissorCount = 1;

	VkPipelineRasterizationStateCreateInfo rasterizer = {};
	rasterizer.sType = VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO;
	rasterizer.polygonMode = (key.flags & 1) ? VK_POLYGON_MODE_LINE : VK_POLYGON_MODE_FILL;
	rasterizer.cullMode = VK_CULL_MODE_NONE; // dynamic
	rasterizer.frontFace = VK_FRONT_FACE_COUNTER_CLOCKWISE;
	rasterizer.lineWidth = 1.0f;

	VkPipelineMultisampleStateCreateInfo multisampling = {};
	multisampling.sType = VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO;
	multisampling.rasterizationSamples = VK_SAMPLE_COUNT_1_BIT;

	VkPipelineDepthStencilStateCreateInfo depthStencil = {};
	depthStencil.sType = VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO;
	depthStencil.depthTestEnable = VK_TRUE;
	depthStencil.depthWriteEnable = VK_TRUE;
	depthStencil.depthCompareOp = VK_COMPARE_OP_LESS_OR_EQUAL;

	auto blendState = VulkanUtil::GetBlendState((BlendMode)key.blendMode);
	VkPipelineColorBlendAttachmentState colorBlendAttachment = {};
	colorBlendAttachment.blendEnable = VK_TRUE;
	colorBlendAttachment.srcColorBlendFactor = blendState.srcColor;
	colorBlendAttachment.dstColorBlendFactor = blendState.dstColor;
	colorBlendAttachment.colorBlendOp = blendState.colorOp;
	colorBlendAttachment.srcAlphaBlendFactor = blendState.srcAlpha;
	colorBlendAttachment.dstAlphaBlendFactor = blendState.dstAlpha;
	colorBlendAttachment.alphaBlendOp = blendState.alphaOp;
	colorBlendAttachment.colorWriteMask = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT |
	                                      VK_COLOR_COMPONENT_B_BIT | VK_COLOR_COMPONENT_A_BIT;

	VkPipelineColorBlendStateCreateInfo colorBlend = {};
	colorBlend.sType = VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO;
	colorBlend.attachmentCount = 1;
	colorBlend.pAttachments = &colorBlendAttachment;

	VkDynamicState dynamicStates[] = {
		VK_DYNAMIC_STATE_VIEWPORT,
		VK_DYNAMIC_STATE_SCISSOR,
		VK_DYNAMIC_STATE_DEPTH_TEST_ENABLE,
		VK_DYNAMIC_STATE_DEPTH_WRITE_ENABLE,
		VK_DYNAMIC_STATE_DEPTH_COMPARE_OP,
		VK_DYNAMIC_STATE_CULL_MODE,
		VK_DYNAMIC_STATE_DEPTH_BIAS_ENABLE,
		VK_DYNAMIC_STATE_DEPTH_BIAS,
		VK_DYNAMIC_STATE_LINE_WIDTH,
		VK_DYNAMIC_STATE_PRIMITIVE_TOPOLOGY,
	};

	VkPipelineDynamicStateCreateInfo dynamicState = {};
	dynamicState.sType = VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO;
	dynamicState.dynamicStateCount = sizeof(dynamicStates) / sizeof(dynamicStates[0]);
	dynamicState.pDynamicStates = dynamicStates;

	VkGraphicsPipelineCreateInfo pipelineCI = {};
	pipelineCI.sType = VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO;
	pipelineCI.stageCount = 2;
	pipelineCI.pStages = stages;
	pipelineCI.pVertexInputState = &vertexInput;
	pipelineCI.pInputAssemblyState = &inputAssembly;
	pipelineCI.pViewportState = &viewportState;
	pipelineCI.pRasterizationState = &rasterizer;
	pipelineCI.pMultisampleState = &multisampling;
	pipelineCI.pDepthStencilState = &depthStencil;
	pipelineCI.pColorBlendState = &colorBlend;
	pipelineCI.pDynamicState = &dynamicState;
	pipelineCI.layout = m_pipelineLayout;
	pipelineCI.renderPass = m_ctx.renderPass;
	pipelineCI.subpass = 0;

	VkPipeline pipeline = VK_NULL_HANDLE;
	if (vkCreateGraphicsPipelines(m_ctx.device, m_vkPipelineCache, 1, &pipelineCI, nullptr, &pipeline) != VK_SUCCESS)
	{
		LOG->Warn("Vulkan: Failed to create pipeline (variant=%u, blend=%u, flags=%u)",
			key.shaderVariant, key.blendMode, key.flags);
		return VK_NULL_HANDLE;
	}

	m_pipelineCache[key] = pipeline;
	return pipeline;
}

void RageDisplay_Vulkan::BindPipelineForCurrentState()
{
	BeginRenderPass();

	auto key = MakeCurrentPipelineKey();
	if (m_bPipelineBound && key == m_lastBoundKey)
		return;

	VkPipeline pipeline = GetOrCreatePipeline(key);
	if (!pipeline) return;

	auto &frame = m_ctx.frames[m_ctx.currentFrame];
	vkCmdBindPipeline(frame.commandBuffer, VK_PIPELINE_BIND_POINT_GRAPHICS, pipeline);
	m_bPipelineBound = true;
	m_lastBoundKey = key;

	// Apply dynamic state
	VkCullModeFlags cullMode = VK_CULL_MODE_NONE;
	if (m_curCullMode == CULL_BACK) cullMode = VK_CULL_MODE_BACK_BIT;
	else if (m_curCullMode == CULL_FRONT) cullMode = VK_CULL_MODE_FRONT_BIT;
	vkCmdSetCullMode(frame.commandBuffer, cullMode);

	bool depthTestEnabled = (m_curZTestMode != ZTEST_OFF);
	vkCmdSetDepthTestEnable(frame.commandBuffer, depthTestEnabled ? VK_TRUE : VK_FALSE);
	vkCmdSetDepthWriteEnable(frame.commandBuffer, m_bZWrite ? VK_TRUE : VK_FALSE);

	VkCompareOp depthOp = VK_COMPARE_OP_ALWAYS;
	if (m_curZTestMode == ZTEST_WRITE_ON_PASS) depthOp = VK_COMPARE_OP_LESS_OR_EQUAL;
	else if (m_curZTestMode == ZTEST_WRITE_ON_FAIL) depthOp = VK_COMPARE_OP_GREATER;
	vkCmdSetDepthCompareOp(frame.commandBuffer, depthOp);

	if (m_fZBias != 0.0f)
	{
		vkCmdSetDepthBiasEnable(frame.commandBuffer, VK_TRUE);
		vkCmdSetDepthBias(frame.commandBuffer, m_fZBias, 0.0f, 0.0f);
	}
	else
	{
		vkCmdSetDepthBiasEnable(frame.commandBuffer, VK_FALSE);
	}

	vkCmdSetLineWidth(frame.commandBuffer, m_fLineWidth);

	// Bind UBO descriptor set (set 0) — required even if lighting is off
	{
		VkDescriptorSetAllocateInfo allocInfo = {};
		allocInfo.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO;
		allocInfo.descriptorPool = frame.descriptorPool;
		allocInfo.descriptorSetCount = 1;
		allocInfo.pSetLayouts = &m_descSetLayoutPerFrame;

		VkDescriptorSet uboSet;
		VkResult uboResult = vkAllocateDescriptorSets(m_ctx.device, &allocInfo, &uboSet);
		if (uboResult != VK_SUCCESS)
		{
			LOG->Warn("Vulkan: Failed to allocate UBO descriptor set (result=%d)", uboResult);
			return;
		}

		// Write UBO data
		uint32_t dynamicOffset = m_uboOffset * m_uboAlignment;

		// Fill UBO with current lighting/material state
		PerFrameUBOData *uboData = (PerFrameUBOData *)((uint8_t *)m_uboMapped + dynamicOffset);
		RageMatrix modelView;
		RageMatrixMultiply(&modelView, GetViewTop(), GetWorldTop());
		memcpy(uboData->modelView, &modelView, 64);

		// Use first enabled light (or defaults)
		for (int i = 0; i < 8; i++)
		{
			if (m_Lights[i].enabled)
			{
				uboData->lightDir[0] = m_Lights[i].dir.x;
				uboData->lightDir[1] = m_Lights[i].dir.y;
				uboData->lightDir[2] = m_Lights[i].dir.z;
				uboData->lightDir[3] = 0;
				memcpy(uboData->lightAmbient, &m_Lights[i].ambient, 16);
				memcpy(uboData->lightDiffuse, &m_Lights[i].diffuse, 16);
				memcpy(uboData->lightSpecular, &m_Lights[i].specular, 16);
				break;
			}
		}
		memcpy(uboData->matEmissive, &m_MatEmissive, 16);
		memcpy(uboData->matAmbient, &m_MatAmbient, 16);
		memcpy(uboData->matDiffuse, &m_MatDiffuse, 16);
		memcpy(uboData->matSpecular, &m_MatSpecular, 16);
		uboData->matShininess = m_fMatShininess;

		VkDescriptorBufferInfo bufInfo = {};
		bufInfo.buffer = m_uboBuffer;
		bufInfo.offset = 0;
		bufInfo.range = sizeof(PerFrameUBOData);

		VkWriteDescriptorSet write = {};
		write.sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
		write.dstSet = uboSet;
		write.dstBinding = 0;
		write.descriptorCount = 1;
		write.descriptorType = VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER_DYNAMIC;
		write.pBufferInfo = &bufInfo;

		vkUpdateDescriptorSets(m_ctx.device, 1, &write, 0, nullptr);

		vkCmdBindDescriptorSets(frame.commandBuffer, VK_PIPELINE_BIND_POINT_GRAPHICS,
			m_pipelineLayout, 0, 1, &uboSet, 1, &dynamicOffset);

		// Advance UBO ring
		m_uboOffset++;
	}
}

void RageDisplay_Vulkan::FlushPushConstants()
{
	auto &frame = m_ctx.frames[m_ctx.currentFrame];

	PushConstants pc;

	// Compose MVP: projection * centering * view * world
	RageMatrix mvp;
	RageMatrixMultiply(&mvp, GetCentering(), GetProjectionTop());
	RageMatrix modelView;
	RageMatrixMultiply(&modelView, GetViewTop(), GetWorldTop());
	RageMatrix combined;
	RageMatrixMultiply(&combined, &mvp, &modelView);
	memcpy(pc.mvp, &combined, 64);

	// Texture matrix
	memcpy(pc.texMatrix, GetTextureTop(), 64);

	vkCmdPushConstants(frame.commandBuffer, m_pipelineLayout,
		VK_SHADER_STAGE_VERTEX_BIT, 0, 128, &pc);
}

void RageDisplay_Vulkan::BindCurrentTexture()
{
	auto &frame = m_ctx.frames[m_ctx.currentFrame];

	VulkanTexture *tex = nullptr;
	if (m_iCurrentTextures[TextureUnit_1] != 0)
	{
		auto it = m_textures.find(m_iCurrentTextures[TextureUnit_1]);
		if (it != m_textures.end())
			tex = &it->second;
	}

	VkImageView view = tex ? tex->imageView : m_dummyTexture.imageView;
	bool wrap = m_bTextureWrapping[TextureUnit_1];
	bool linear = m_bTextureFiltering[TextureUnit_1];
	VkSampler sampler = GetSampler(wrap, linear);

	// Allocate descriptor set for this texture
	VkDescriptorSetAllocateInfo allocInfo = {};
	allocInfo.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO;
	allocInfo.descriptorPool = frame.descriptorPool;
	allocInfo.descriptorSetCount = 1;
	allocInfo.pSetLayouts = &m_descSetLayoutTexture;

	VkDescriptorSet descSet;
	VkResult dsResult = vkAllocateDescriptorSets(m_ctx.device, &allocInfo, &descSet);
	if (dsResult != VK_SUCCESS)
	{
		LOG->Warn("Vulkan: Failed to allocate texture descriptor set (result=%d)", dsResult);
		return;
	}

	VkDescriptorImageInfo imageInfo = {};
	imageInfo.sampler = sampler;
	imageInfo.imageView = view;
	imageInfo.imageLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;

	VkWriteDescriptorSet write = {};
	write.sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
	write.dstSet = descSet;
	write.dstBinding = 0;
	write.descriptorCount = 1;
	write.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
	write.pImageInfo = &imageInfo;

	vkUpdateDescriptorSets(m_ctx.device, 1, &write, 0, nullptr);

	vkCmdBindDescriptorSets(frame.commandBuffer, VK_PIPELINE_BIND_POINT_GRAPHICS,
		m_pipelineLayout, 1, 1, &descSet, 0, nullptr);
}

void RageDisplay_Vulkan::UploadVertices(const RageSpriteVertex v[], int iNumVerts)
{
	auto &frame = m_ctx.frames[m_ctx.currentFrame];
	uint32_t size = iNumVerts * sizeof(RageSpriteVertex);

	if (frame.vertexOffset + size > frame.vertexCapacity)
	{
		LOG->Warn("Vulkan: Vertex ring buffer overflow (%u + %u > %u)",
			frame.vertexOffset, size, frame.vertexCapacity);
		return;
	}

	memcpy((uint8_t *)frame.vertexMapped + frame.vertexOffset, v, size);

	VkDeviceSize offset = frame.vertexOffset;
	vkCmdBindVertexBuffers(frame.commandBuffer, 0, 1, &frame.vertexBuffer, &offset);

	frame.vertexOffset += size;
}

void RageDisplay_Vulkan::EnsureQuadIBO(int iNumQuads)
{
	if (iNumQuads <= m_iQuadIBOSize)
		return;

	int newSize = std::max(iNumQuads, std::max(m_iQuadIBOSize * 2, 256));

	// Generate index data
	std::vector<uint16_t> indices(newSize * 6);
	for (int i = 0; i < newSize; i++)
	{
		indices[i * 6 + 0] = i * 4 + 0;
		indices[i * 6 + 1] = i * 4 + 1;
		indices[i * 6 + 2] = i * 4 + 2;
		indices[i * 6 + 3] = i * 4 + 0;
		indices[i * 6 + 4] = i * 4 + 2;
		indices[i * 6 + 5] = i * 4 + 3;
	}

	// Destroy old
	if (m_quadIBO)
		vmaDestroyBuffer(m_ctx.allocator, m_quadIBO, m_quadIBOAlloc);

	VkBufferCreateInfo bufCI = {};
	bufCI.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
	bufCI.size = indices.size() * sizeof(uint16_t);
	bufCI.usage = VK_BUFFER_USAGE_INDEX_BUFFER_BIT;

	VmaAllocationCreateInfo allocCI = {};
	allocCI.usage = VMA_MEMORY_USAGE_AUTO;
	allocCI.flags = VMA_ALLOCATION_CREATE_HOST_ACCESS_SEQUENTIAL_WRITE_BIT;

	vmaCreateBuffer(m_ctx.allocator, &bufCI, &allocCI, &m_quadIBO, &m_quadIBOAlloc, nullptr);

	void *mapped;
	vmaMapMemory(m_ctx.allocator, m_quadIBOAlloc, &mapped);
	memcpy(mapped, indices.data(), bufCI.size);
	vmaUnmapMemory(m_ctx.allocator, m_quadIBOAlloc);

	m_iQuadIBOSize = newSize;
}

